const mergeSpecs = (baseSpecs = [], extraSpecs = []) => {
  const seen = new Set(baseSpecs.map(([label]) => label));
  return [...baseSpecs, ...extraSpecs.filter(([label]) => !seen.has(label))];
};

const mergeSources = (baseSources = [], extraSources = []) => {
  const seen = new Set(baseSources.map((entry) => entry.url));
  return [...baseSources, ...extraSources.filter((entry) => !seen.has(entry.url))];
};

const p = (item) => {
  const previousPrice = priceOverrides[item.id] || item.price || pendingPrice();
  const price = providedPriceRanges[item.id]
    ? { ...providedPriceRanges[item.id], previousPrice }
    : previousPrice;
  const priceSource =
    price.sourceUrl && price.sourceName ? source(price.sourceName, price.sourceUrl, priceSourceType(price)) : null;
  const baseSources = priceSource
    ? [priceSource, ...(item.sources || []).filter((entry) => entry.url !== price.sourceUrl)]
    : item.sources;
  return {
    ...item,
    image: item.image || image(`${item.brand} ${item.model}`),
    price,
    specs: mergeSpecs(item.specs, specOverrides[item.id] || []),
    sources: mergeSources(baseSources, extraSpecSources[item.id] || []),
    verified: item.verified || "parcial",
  };
};

